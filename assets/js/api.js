(function () {
  "use strict";
  const config = window.REVIEWER_CONFIG;

  const demoResult = {
    summary: "Demo review only: these example findings are illustrative and were not generated by the Python agent. Connect the API to display real findings.",
    findings: [
      { id: "demo-1", severity: "critical", title: "Missing input validation", message: "The function assumes the input is an array. Invalid input may cause a runtime error or unexpected behavior.", file: "snippet.js", line: 1, suggestion: "if (!Array.isArray(items)) {\n  throw new TypeError('items must be an array');\n}" },
      { id: "demo-2", severity: "warning", title: "Consider a simpler iteration", message: "A built-in array method could make the intent easier to read. Treat this as a style suggestion, not necessarily a defect.", file: "snippet.js", line: 2, suggestion: "return items.reduce((sum, item) => sum + item, 0);" },
      { id: "demo-3", severity: "suggestion", title: "Add a focused unit test", message: "Consider testing empty input, valid values, and unexpected input to document the expected behavior.", file: "snippet.js", line: 1, suggestion: "// Example test cases: [], [1, 2], and invalid input." }
    ]
  };

  function normalizeResult(payload) {
    // Expected adapter contract. Map the Python API response here if its schema differs.
    const rawFindings = Array.isArray(payload?.findings) ? payload.findings : Array.isArray(payload?.issues) ? payload.issues : null;
    if (!rawFindings) throw new Error("The API response did not include a findings array. Update normalizeResult() to match the Python response schema.");
    const findings = rawFindings.map((item, index) => {
      const rawSeverity = String(item.severity || item.priority || "suggestion").toLowerCase();
      const severity = ["critical", "error", "high", "blocker"].includes(rawSeverity) ? "critical" : ["warning", "medium", "moderate"].includes(rawSeverity) ? "warning" : "suggestion";
      return {
        id: String(item.id ?? index + 1), severity,
        title: String(item.title ?? item.name ?? item.rule ?? "Code finding"),
        message: String(item.message ?? item.description ?? item.explanation ?? "No explanation was provided."),
        file: String(item.file ?? item.path ?? item.filename ?? ""),
        line: Number.isFinite(Number(item.line ?? item.line_number)) ? Number(item.line ?? item.line_number) : null,
        suggestion: String(item.suggestion ?? item.suggested_fix ?? item.fix ?? "")
      };
    });
    return { summary: String(payload.summary ?? payload.overall_summary ?? "Review completed."), findings };
  }

  async function request(path, body) {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), config.REQUEST_TIMEOUT_MS);
    try {
      const response = await fetch(`${config.API_BASE_URL.replace(/\/$/, "")}${path}`, {
        method: "POST", headers: { "Content-Type": "application/json", "Accept": "application/json" },
        body: JSON.stringify(body), signal: controller.signal
      });
      const payload = await response.json().catch(() => ({}));
      if (!response.ok) throw new Error(payload.detail || payload.message || `API request failed (${response.status}).`);
      return normalizeResult(payload);
    } catch (error) {
      if (error.name === "AbortError") throw new Error("The review request timed out. Please try again.");
      if (error instanceof TypeError) throw new Error("Could not reach the Python API. Check that the backend is running, the API URL is correct, and CORS allows this frontend origin.");
      throw error;
    } finally { clearTimeout(timeout); }
  }

  async function reviewCode({ code, filename, language }) {
    if (config.USE_MOCK_API) return { ...demoResult, findings: demoResult.findings.map(x => ({ ...x })), source: "demo" };
    return { ...(await request(config.CODE_REVIEW_ENDPOINT, { code, filename, language })), source: "api" };
  }

  async function reviewPullRequest({ url, language }) {
    if (config.USE_MOCK_API) {
      // Deliberately do not pretend to fetch a real pull request in demo mode.
      return { ...demoResult, findings: demoResult.findings.map(x => ({ ...x })), summary: "Demo only: the PR URL was validated, but GitHub was not contacted. Configure the Python PR endpoint for a real review.", source: "demo" };
    }
    return { ...(await request(config.PR_REVIEW_ENDPOINT, { url, language })), source: "api" };
  }

  window.ReviewerAPI = { reviewCode, reviewPullRequest, normalizeResult };
})();
